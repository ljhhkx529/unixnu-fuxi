#!/usr/bin/env python3
"""Generate the typed Fuxi audio board data consumed by the kernel archive."""
from __future__ import annotations

import argparse
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BINDING = ROOT / "facts/audio/binding.toml"
STATE = {"unverified": "FuxiAudioUnverified", "chosen": "FuxiAudioChosen", "verified": "FuxiAudioVerified"}


def entry(data: dict, dotted: str) -> dict:
    value = data
    for part in dotted.split("."):
        value = value[part]
    if not isinstance(value, dict) or not {"value", "state", "evidence"} <= value.keys():
        raise ValueError(f"{dotted}: not a binding leaf")
    if value["state"] not in STATE:
        raise ValueError(f"{dotted}: unknown state {value['state']!r}")
    return value


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_value(value) -> str:
    if isinstance(value, str):
        return c_string(value)
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return f"0x{value:x}u" if value >= 10 else f"{value}u"
    raise ValueError(f"unsupported C value {value!r}")


def leaves(data: dict, prefix: str = ""):
    for name, value in data.items():
        path = f"{prefix}.{name}" if prefix else name
        if isinstance(value, dict) and {"value", "state", "evidence"} <= value.keys():
            yield path, value
        elif isinstance(value, dict):
            yield from leaves(value, path)


def designated(data: dict, names: list[tuple[str, str]], indent: str = "        ") -> str:
    return "\n".join(f"{indent}.{field} = {c_value(entry(data, path)['value'])}," for field, path in names)


ADSP = [
    ("carveout_base", "adsp.carveout.carveout_base"), ("carveout_size", "adsp.carveout.carveout_size"),
    ("state_entry", "adsp.entries.state_entry"), ("ready_entry", "adsp.entries.ready_entry"),
    ("fatal_entry", "adsp.entries.fatal_entry"), ("ready_value", "adsp.values.ready_value"),
    ("fatal_value", "adsp.values.fatal_value"), ("load_state_message", "adsp.entries.load_state_message"),
    ("mailbox_timeout", "adsp.timeouts.mailbox_timeout"), ("ready_timeout", "adsp.timeouts.ready_timeout"),
    ("link_timeout", "adsp.timeouts.link_timeout"),
]
PLATFORM = [(name, f"adsp.platform.{name}") for name in (
    "smem_base", "smem_size", "tcsr_mutex", "ipcc_base", "ipcc_spi", "aoss_base", "aoss_size",
    "rsc_base", "rsc_size", "rsc_tcs_offset", "rsc_spi", "cmd_db_base", "cmd_db_size", "remote_pid",
    "smp2p_in_item", "smp2p_out_item", "smp2p_crash_item", "glink_desc_item", "glink_tx_item",
    "glink_rx_item", "glink_fifo_bytes", "pas_adsp", "pas_dtb", "dtb_carveout_base", "dtb_carveout_size",
    "glink_channel", "glink_intent_size", "glink_intent_count")]
PLATFORM.append(("gpr_port", "path.gpr_port"))
MI2S = [(name, f"interface.mi2s.{name}") for name in
         ("port_id", "sck_gpio", "ws_gpio", "data_out_gpio", "data_in_gpio")]
I2C = [(name, f"interface.i2c8.{name}") for name in
       ("mmio_base", "frequency_hz", "sda_gpio", "scl_gpio")]
CS35 = [(name, f"amp.registers.{name}") for name in (
    "reg_device_id", "reg_revision", "reg_global_enables", "reg_block_enables", "reg_asp_enables", "reg_asp_ctrl",
    "reg_boost_peak", "reg_boost_cap", "reg_pll_ctrl", "reg_mute", "reg_irq1_eint1", "reg_irq1_eint2",
    "reg_irq1_mask1", "device_id_value", "revision_value", "enable_value", "asp_slot_value", "boost_peak_value",
    "boost_cap_value", "pll_value", "irq_mask_value", "mute_on", "mute_off", "clock_settle_ms")]
AMP = [(name, name) for name in ("channel", "i2c_address", "reset_gpio", "irq_gpio")]


def render(data: dict) -> str:
    rows = list(leaves(data))
    counts = {name: sum(row[1]["state"] == name for row in rows) for name in STATE}
    metadata = "\n".join(
        f"    {{{c_string(path)}, {c_string(str(item['evidence']))}, {STATE[item['state']]} }}," for path, item in rows)
    return f"""/* Generated by scripts/gen-fuxi-audio-binding.py; do not edit. */
static const FuxiAudioFieldInfo gFuxiAudioFields[] = {{
{metadata}
}};

static const FuxiAudioBinding gFuxiAudioBinding = {{
    .adsp = {{
{designated(data, ADSP)}
    }},
    .platform = {{
{designated(data, PLATFORM)}
    }},
    .mi2s = {{
{designated(data, MI2S)}
    }},
    .i2c8 = {{
{designated(data, I2C)}
    }},
    .cs35l41 = {{
{designated(data, CS35)}
    }},
    .amplifiers = {{
        {{
{designated(data, [(field, 'amp.b.' + path) for field, path in AMP], '            ')}
        }},
        {{
{designated(data, [(field, 'amp.t.' + path) for field, path in AMP], '            ')}
        }},
    }},
    .fields = gFuxiAudioFields,
    .field_count = (uint32_t)(sizeof gFuxiAudioFields / sizeof gFuxiAudioFields[0]),
    .state_count = {{{counts['unverified']}u, {counts['chosen']}u, {counts['verified']}u}},
}};
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--binding", type=Path, default=DEFAULT_BINDING)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = tomllib.loads(args.binding.read_text())
    output = render(data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)
    print(f"generated {args.output} ({sum(1 for _ in leaves(data))} fields)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
